const WEEKDAYS = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday"];

function weekdaySchedule(start = "08:00", midEnd = "12:00", midStart = "13:30", end = "17:00"): DaySchedule[] {
  const all = ["sunday", ...WEEKDAYS];
  return all.map((day) => ({
    day,
    enabled: WEEKDAYS.includes(day),
    shifts: WEEKDAYS.includes(day)
      ? [
          { startTime: start, endTime: midEnd },
          { startTime: midStart, endTime: end },
        ]
      : [],
  }));
}

